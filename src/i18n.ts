export const dict = { es, en };
export type MsgKey = Key;
export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  return (key, vars) =>
    dict[lang][key].replace(/\{(\w+)\}/g, (_, k) => (vars && k in vars ? String(vars[k]) : `{${k}}`));
}

export function list(items: string[], lang: Lang) {
  if (items.length < 2) return items.join("");
  return items.slice(0, -1).join(", ") + ` ${dict[lang].and} ` + items[items.length - 1];
}

const FRAC: [number, string][] = [[1 / 2, "½"], [1 / 3, "⅓"], [2 / 3, "⅔"], [1 / 4, "¼"], [3 / 4, "¾"]];
export function nice(x: number, lang: Lang) {
  const w = Math.floor(x + 1e-9), f = x - w;
  if (f < 1e-6) return String(w);
  for (const [v, g] of FRAC) if (Math.abs(f - v) < 1e-6) return (w || "") + g;
  return x.toLocaleString(lang, { maximumFractionDigits: 1 });
}
